/**
 * Builds the DTCG tokens in /tokens into every platform's theme.
 *
 *   node build-tokens/build.ts
 *
 * Outputs, all committed and all marked as generated:
 *
 *   packages/ui/src/styles/tokens.css            CSS custom properties, both themes
 *   packages/ui/src/tokens/tokens.ts             typed semantic token names
 *   packages/ui/src/motion/tokens.ts             motion values as numbers, for Motion
 *   packages/flutter/lib/src/tokens/*.dart       constants per theme, WabiColors, base tokens
 *
 * Style Dictionary resolves and validates; the formats live here, written out explicitly,
 * because each output has a shape no built-in format produces (two themes in one CSS file,
 * a ThemeExtension with lerp). The per-theme constant classes use the built-in
 * `flutter/class.dart` format.
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import type { TransformedToken } from 'style-dictionary/types'
import {
  createDictionary,
  isSemantic,
  loadTheme,
  ROOT,
  referencePath,
  THEMES,
  type Theme,
  type ThemeTokens,
} from './lib.ts'

const UI = join(ROOT, 'packages/ui/src')
const FLUTTER_TOKENS = join(ROOT, 'packages/flutter/lib/src/tokens')

const HEADER = 'Generated by build-tokens from /tokens. Do not edit: change the JSON and rebuild.'

const written: string[] = []

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  written.push(path)
}

// Naming -----------------------------------------------------------------------------------

/**
 * The CSS name of a token path. Colour primitives drop their `color` group so the names
 * stay as they were before the JSON existed: `--ws-neutral-light-1`, `--ws-white`.
 */
function cssName(path: string[]): string {
  if (path[0] === 'spring') return 'ws-ease-spring'
  const parts = path[0] === 'color' ? path.slice(1) : path
  return `ws-${parts.join('-')}`
}

function camel(parts: string[]): string {
  const words = parts.flatMap((part) => part.split('-'))
  return words
    .map((word, index) => (index === 0 ? word : word.charAt(0).toUpperCase() + word.slice(1)))
    .join('')
}

// Value helpers ----------------------------------------------------------------------------

function px(value: unknown): number {
  const match = String(value).match(/^(-?[\d.]+)px$/)
  if (!match?.[1]) throw new Error(`Expected a px dimension, got ${String(value)}`)
  return Number(match[1])
}

function ms(value: unknown): number {
  const match = String(value).match(/^([\d.]+)ms$/)
  if (!match?.[1]) throw new Error(`Expected a duration in ms, got ${String(value)}`)
  return Number(match[1])
}

/** Trims float noise: 0.6940000001 → 0.694. */
function num(value: number): string {
  return String(Number(value.toFixed(4)))
}

// CSS --------------------------------------------------------------------------------------

/**
 * px becomes rem, so sizes follow the user's font size setting. Two exceptions stay in px:
 * motion distances, which are offsets rather than sizes, and the "full" radius, which is a
 * sentinel rather than a length.
 */
function cssDimension(token: TransformedToken): string {
  const value = px(token.$value)
  if (token.path[0] === 'distance' || value >= 9999) return `${num(value)}px`
  return `${num(value / 16)}rem`
}

function cssValue(token: TransformedToken): string {
  const ref = referencePath(token)
  if (ref) return `var(--${cssName(ref)})`

  switch (token.$type) {
    case 'color':
    case 'duration':
      return String(token.$value)
    case 'dimension':
      return cssDimension(token)
    case 'number':
    case 'fontWeight':
      return String(token.$value)
    case 'fontFamily':
      return (token.$value as string[])
        .map((family) => (family.includes(' ') ? `"${family}"` : family))
        .join(', ')
    case 'cubicBezier':
      return `cubic-bezier(${(token.$value as number[]).join(', ')})`
    case 'spring': {
      const linear = (token.$extensions as Record<string, { cssLinear?: string }>)?.[
        'dev.wabi-sabi'
      ]?.cssLinear
      if (!linear) throw new Error('The spring token needs a cssLinear extension for CSS')
      return linear
    }
    default:
      throw new Error(`No CSS conversion for $type ${token.$type} (${token.path.join('.')})`)
  }
}

function cssDeclarations(tokens: TransformedToken[], indent: string): string {
  const lines: string[] = []
  let group = ''
  for (const token of tokens) {
    const head =
      token.path[0] === 'color' && token.path.length > 2
        ? token.path.slice(0, 2).join('.')
        : token.path[0]
    if (head !== group && !isSemantic(token)) {
      if (group) lines.push('')
      lines.push(`${indent}/* ${head} */`)
      group = head ?? ''
    }
    lines.push(`${indent}--${cssName(token.path)}: ${cssValue(token)};`)
  }
  return lines.join('\n')
}

function buildCss(themes: Record<Theme, ThemeTokens>): void {
  const base = themes.light.all.filter((token) => !isSemantic(token))
  const light = cssDeclarations(themes.light.semantic, '  ')
  const dark = cssDeclarations(themes.dark.semantic, '  ')
  const darkNested = cssDeclarations(themes.dark.semantic, '    ')

  write(
    join(UI, 'styles/tokens.css'),
    `/*
 * ${HEADER}
 *
 * Three layers. Primitives and base tokens are declared once on :root. Semantic tokens are
 * what components consume: the light set on :root, the dark set under [data-theme="dark"]
 * and, when no theme is chosen explicitly, under prefers-color-scheme. Both sets have the
 * same names and point at different primitives.
 *
 * Components must never reference a colour primitive. Enforced by Stylelint.
 */

:root {
  color-scheme: light;

${cssDeclarations(base, '  ')}

  /* semantic — light */
${light}
}

/* Re-declared so a light island inside a dark page resolves to light values. */
[data-theme="light"] {
  color-scheme: light;

${light}
}

[data-theme="dark"] {
  color-scheme: dark;

${dark}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;

${darkNested}
  }
}
`,
  )
}

// TypeScript -------------------------------------------------------------------------------

function buildTypeScript(themes: Record<Theme, ThemeTokens>): void {
  const names = themes.light.semantic.map((token) => token.path.join('-'))

  write(
    join(UI, 'tokens/tokens.ts'),
    `/**
 * ${HEADER}
 *
 * The semantic colour tokens, by name. Use these to reference a token from TypeScript
 * with autocomplete and a compile error on a typo; the values themselves live in CSS, so
 * they follow the active theme.
 */

export const semanticColorTokens = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const

export type SemanticColorToken = (typeof semanticColorTokens)[number]

/** \`cssVar.canvas\` is \`'var(--ws-canvas)'\`. */
export const cssVar = {
${names.map((name) => `  '${name}': 'var(--ws-${name})',`).join('\n')}
} as const satisfies Record<SemanticColorToken, string>
`,
  )

  const all = themes.light.all
  const group = (name: string) => all.filter((token) => token.path[0] === name)
  const spring = all.find((token) => token.path[0] === 'spring')
  const springValue = spring?.$value as { stiffness: number; damping: number; mass: number }
  const doc = (token: TransformedToken, indent = '  ') =>
    token.$description ? `${indent}/** ${token.$description} */\n` : ''

  write(
    join(UI, 'motion/tokens.ts'),
    `/**
 * ${HEADER}
 *
 * Motion tokens as values usable inside Motion, which needs numbers rather than CSS
 * strings. The same tokens reach CSS as custom properties through styles/tokens.css, from
 * the same JSON, so the two cannot drift apart.
 */

/** Durations in seconds, which is the unit Motion expects. */
export const duration = {
${group('duration')
  .map((t) => `${doc(t)}  ${t.path[1]}: ${num(ms(t.$value) / 1000)},`)
  .join('\n')}
} as const

/**
 * Cubic bezier control points, in Motion's array form.
 *
 * There is no ease-in curve on purpose. Ease-in starts slow, delaying the moment the user
 * is actually watching, so it is never right for UI.
 */
export const ease = {
${group('ease')
  .map((t) => `${doc(t)}  ${t.path[1]}: [${(t.$value as number[]).join(', ')}],`)
  .join('\n')}
} as const

/** Spring configuration, for movement that should feel physical rather than timed. */
export const spring = {
  type: 'spring',
  stiffness: ${springValue.stiffness},
  damping: ${springValue.damping},
  mass: ${springValue.mass},
} as const

/** Offsets, in pixels, for movement that accompanies a fade. */
export const distance = {
${group('distance')
  .map((t) => `  ${t.path[1]}: ${num(px(t.$value))},`)
  .join('\n')}
} as const

export type Duration = keyof typeof duration
export type Ease = keyof typeof ease
export type Distance = keyof typeof distance
`,
  )
}

// Dart -------------------------------------------------------------------------------------

const DART_HEADER = `// ${HEADER}
//
// dart format off`

function dartColor(value: unknown): string {
  const hex = String(value).replace('#', '').toUpperCase()
  if (hex.length === 6) return `Color(0xFF${hex})`
  if (hex.length === 8) return `Color(0x${hex.slice(6)}${hex.slice(0, 6)})`
  throw new Error(`Unsupported colour ${String(value)}`)
}

function dartDoc(token: TransformedToken, indent = '  '): string {
  return token.$description ? `${indent}/// ${token.$description}\n` : ''
}

function buildWabiColors(themes: Record<Theme, ThemeTokens>): void {
  const fields = themes.light.semantic.map((token) => ({
    token,
    name: camel(token.path),
    path: token.path.join('.'),
  }))
  const darkByPath = new Map(themes.dark.semantic.map((t) => [t.path.join('.'), t]))
  const instance = (theme: Theme) =>
    fields
      .map(({ name, path, token }) => {
        const source = theme === 'light' ? token : darkByPath.get(path)
        if (!source) throw new Error(`${path} is missing from semantic.dark.json`)
        return `    ${name}: ${dartColor(source.$value)},`
      })
      .join('\n')

  write(
    join(FLUTTER_TOKENS, 'wabi_colors.dart'),
    `${DART_HEADER}

import 'package:flutter/material.dart';

/// The semantic colours, one field per token in /tokens/semantic.*.json.
///
/// Registered on \`ThemeData.extensions\`; components read it with
/// \`Theme.of(context).extension<WabiColors>()!\`, never a colour constant.
@immutable
class WabiColors extends ThemeExtension<WabiColors> {
  const WabiColors({
${fields.map(({ name }) => `    required this.${name},`).join('\n')}
  });

${fields.map(({ name, token }) => `${dartDoc(token)}  final Color ${name};`).join('\n\n')}

  static const light = WabiColors(
${instance('light')}
  );

  static const dark = WabiColors(
${instance('dark')}
  );

  @override
  WabiColors copyWith({
${fields.map(({ name }) => `    Color? ${name},`).join('\n')}
  }) {
    return WabiColors(
${fields.map(({ name }) => `      ${name}: ${name} ?? this.${name},`).join('\n')}
    );
  }

  @override
  WabiColors lerp(covariant ThemeExtension<WabiColors>? other, double t) {
    if (other is! WabiColors) return this;
    return WabiColors(
${fields.map(({ name }) => `      ${name}: Color.lerp(${name}, other.${name}, t)!,`).join('\n')}
    );
  }
}
`,
  )
}

/** Which Dart class each top-level token group lands in. Unknown groups fail the build. */
const DART_GROUPS: Record<string, { className: string; doc: string }> = {
  space: { className: 'WabiSpace', doc: '4px spacing scale, in logical pixels.' },
  radius: { className: 'WabiRadius', doc: 'Corner radii, in logical pixels.' },
  font: { className: 'WabiFontFamily', doc: 'Font stacks. The library ships no fonts.' },
  text: { className: 'WabiFontSize', doc: 'Font sizes: modular scale, ratio 1.2 from 16.' },
  leading: { className: 'WabiLineHeight', doc: 'Line heights, as multipliers.' },
  weight: { className: 'WabiFontWeight', doc: 'Font weights. Two are enough.' },
  icon: { className: 'WabiIcon', doc: 'Icon size and stroke weight.' },
  duration: { className: 'WabiDuration', doc: 'Motion durations.' },
  ease: { className: 'WabiEasing', doc: 'Easing curves. There is deliberately no ease-in.' },
  spring: { className: 'WabiSpring', doc: 'Spring for physical, untimed movement.' },
  distance: { className: 'WabiDistance', doc: 'Offsets for movement accompanying a fade.' },
  button: { className: 'WabiButtonTokens', doc: 'Button component tokens.' },
}

function dartIdentifier(token: TransformedToken): string {
  const [group, ...rest] = token.path
  if (rest.length === 0) return 'value'
  // An identifier cannot start with a digit: space.1 becomes space1, text.2xl text2xl.
  return /^\d/.test(rest[0] ?? '') ? camel([group ?? '', ...rest]) : camel(rest)
}

function dartConstant(token: TransformedToken): string {
  const name = dartIdentifier(token)
  switch (token.$type) {
    case 'dimension':
      return `static const double ${name} = ${num(px(token.$value))};`
    case 'number':
      return `static const double ${name} = ${num(Number(token.$value))};`
    case 'fontWeight':
      return `static const FontWeight ${name} = FontWeight.w${token.$value};`
    case 'fontFamily':
      return `static const List<String> ${name} = [${(token.$value as string[]).map((f) => `'${f}'`).join(', ')}];`
    case 'duration':
      return `static const Duration ${name} = Duration(milliseconds: ${num(ms(token.$value))});`
    case 'cubicBezier':
      return `static const Cubic ${name} = Cubic(${(token.$value as number[]).join(', ')});`
    case 'spring': {
      const { stiffness, damping, mass } = token.$value as Record<string, number>
      return `static const SpringDescription ${name} = SpringDescription(mass: ${mass}, stiffness: ${stiffness}, damping: ${damping});`
    }
    default:
      throw new Error(`No Dart conversion for $type ${token.$type} (${token.path.join('.')})`)
  }
}

function buildBaseTokens(themes: Record<Theme, ThemeTokens>): void {
  const base = themes.light.all.filter((t) => !isSemantic(t) && t.path[0] !== 'color')
  const classes = new Map<string, TransformedToken[]>()
  for (const token of base) {
    const group = token.path[0] ?? ''
    if (!DART_GROUPS[group]) throw new Error(`Add the token group "${group}" to DART_GROUPS`)
    classes.set(group, [...(classes.get(group) ?? []), token])
  }

  const body = [...classes]
    .map(([group, tokens]) => {
      const { className, doc } = DART_GROUPS[group] as { className: string; doc: string }
      const members = tokens.map((t) => `${dartDoc(t)}  ${dartConstant(t)}`).join('\n')
      return `/// ${doc}\nabstract final class ${className} {\n${members}\n}`
    })
    .join('\n\n')

  write(
    join(FLUTTER_TOKENS, 'wabi_base_tokens.dart'),
    `${DART_HEADER}

import 'package:flutter/physics.dart';
import 'package:flutter/widgets.dart';

${body}
`,
  )
}

/** The per-theme constant classes, through Style Dictionary's built-in format. */
async function buildDartConstants(): Promise<void> {
  for (const theme of THEMES) {
    const className = `WabiTokens${theme === 'light' ? 'Light' : 'Dark'}`
    const destination = `wabi_tokens_${theme}.dart`
    const sd = createDictionary(theme, {
      flutter: {
        transformGroup: 'flutter',
        buildPath: `${FLUTTER_TOKENS}/`,
        files: [
          {
            destination,
            format: 'flutter/class.dart',
            // Semantic colours only. Primitives would put both modes' scales in each
            // class, and the base tokens are theme-independent: they live in
            // wabi_base_tokens.dart with proper Dart types.
            filter: (token) => isSemantic(token),
            options: { className, showFileHeader: false },
          },
        ],
      },
    })
    await sd.buildPlatform('flutter')
    written.push(join(FLUTTER_TOKENS, destination))
  }
}

// Main -------------------------------------------------------------------------------------

const themes = {
  light: await loadTheme('light'),
  dark: await loadTheme('dark'),
} satisfies Record<Theme, ThemeTokens>

const lightNames = themes.light.semantic.map((t) => t.path.join('.')).join()
const darkNames = themes.dark.semantic.map((t) => t.path.join('.')).join()
if (lightNames !== darkNames) {
  throw new Error('semantic.light.json and semantic.dark.json must declare the same names')
}

buildCss(themes)
buildTypeScript(themes)
buildWabiColors(themes)
buildBaseTokens(themes)
await buildDartConstants()

// Format the web outputs with the repository's own formatter, so a rebuild never produces
// a diff that a commit hook would then rewrite. Dart files opt out with `dart format off`.
const webOutputs = written.filter((path) => /\.(ts|css)$/.test(path))
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', ...webOutputs], {
  cwd: ROOT,
  stdio: ['ignore', 'ignore', 'inherit'],
})

for (const path of written) console.log(`  ${relative(ROOT, path)}`)
